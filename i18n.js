(function () {
  var KEY = "bw-lang";
  function lang() {
    try { return localStorage.getItem(KEY) || "en"; } catch (e) { return "en"; }
  }
  function apply(l) {
    document.documentElement.lang = l;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var t = window.I18N[el.getAttribute("data-i18n")];
      if (t) el.textContent = t[l] || t.en;
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      var t = window.I18N[el.getAttribute("data-i18n-ph")];
      if (t) el.placeholder = t[l] || t.en;
    });
    document.querySelectorAll(".lang button").forEach(function (b) {
      b.classList.toggle("on", b.getAttribute("data-lang") === l);
    });
    document.querySelectorAll("[data-lang-block]").forEach(function (el) {
      el.style.display = el.getAttribute("data-lang-block") === l ? "" : "none";
    });
  }
  window.setLang = function (l) {
    try { localStorage.setItem(KEY, l); } catch (e) {}
    apply(l);
  };
  document.addEventListener("DOMContentLoaded", function () { apply(lang()); });
})();
